import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

const state = async (page: Page) => (await page.request.get('/_test/state')).json()
const overview = (page: Page) => page.getByRole('region', { name: 'What you have', exact: true })
async function buyMilk(page: Page) {
  await page.goto('/#inventory')
  await page.getByRole('button', { name: 'I bought some', exact: true }).click()
  await page.getByLabel('Find a product', { exact: true }).fill('Milk')
  await page.getByRole('list', { name: 'Product results' }).getByRole('button', { name: 'Milk', exact: false }).click()
  await expect(page.getByText('Currently have:', { exact: false })).toContainText('3 bottle')
  await page.getByLabel('Quantity bought', { exact: false }).fill('2')
  await page.getByLabel('Where will you keep it?').selectOption('2')
  await page.getByLabel('Package date (best before or use by)').fill('2031-12-01')
  await page.getByLabel('Note (optional)').fill('New shopping')
}

test.beforeEach(async ({ request }) => { expect((await request.post('/_test/reset')).ok()).toBeTruthy() })

test('inventory navigation searches and retains batches locations dates and opened state', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('link', { name: 'Inventory', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your inventory.' })).toBeVisible()
  await expect(overview(page)).toContainText('3 bottle')
  await expect(overview(page)).toContainText('Fridge')
  await expect(overview(page)).toContainText('Cupboard')
  await expect(overview(page)).toContainText('opened')
  await expect(overview(page)).toContainText('2030')
  await page.getByLabel('Search inventory').fill('no match')
  await expect(page.getByText('No matching products in your inventory.')).toBeVisible()
  await page.getByLabel('Search inventory').fill('mIL')
  await expect(overview(page).getByRole('heading', { name: 'Milk', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath('inventory-overview.png'), fullPage: true })
  expect((await state(page)).requests.filter(([method]: string[]) => method !== 'GET')).toEqual([])
})

test('addition requires review and confirmation and updates stock without grocery mutations', async ({ page }, testInfo) => {
  await buyMilk(page)
  await page.getByRole('button', { name: 'Review addition', exact: true }).click()
  const review = page.getByRole('region', { name: 'Review inventory change' })
  await expect(review).toContainText('Add 2 bottle of Milk?')
  await expect(review).toContainText('Cupboard')
  await expect(review).toContainText('5 bottle')
  await expect(page.getByRole('button', { name: 'Confirm addition', exact: true })).toBeFocused()
  expect((await state(page)).requests.filter(([method]: string[]) => method !== 'GET')).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('inventory-review.png'), fullPage: true })
  await page.getByRole('button', { name: 'Confirm addition', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Added 2 bottle of Milk. You now have 5 bottle.')
  await expect(overview(page)).toContainText('5 bottle')
  const current = await state(page)
  expect(current.items).toHaveLength(2)
  expect(current.requests.filter(([method]: string[]) => method !== 'GET').map((entry: string[]) => entry[1])).toEqual(['stock/products/10/add'])
  expect(current.stock[2]).toMatchObject({ product_id: 10, amount: 2, location_id: 2, best_before_date: '2031-12-01', note: 'New shopping' })
})

test('consumption explicitly selects a batch and confirms before changing it', async ({ page }) => {
  await page.goto('/#inventory')
  await page.getByRole('button', { name: 'Use some Milk', exact: true }).click()
  await page.getByLabel('Which batch did you use?').selectOption('202')
  await page.getByLabel('Quantity used', { exact: false }).fill('0.5')
  await page.getByRole('button', { name: 'Review use', exact: true }).click()
  const review = page.getByRole('region', { name: 'Review inventory change' })
  await expect(review).toContainText('Use 0.5 bottle of Milk?')
  await expect(review).toContainText('Cupboard')
  await expect(review).toContainText('2.5 bottle')
  await page.getByRole('button', { name: 'Go back', exact: true }).click()
  expect((await state(page)).stock[1].amount).toBe(1)
  await page.getByRole('button', { name: 'Review use', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm use', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Used 0.5 bottle of Milk. You now have 2.5 bottle.')
  const current = await state(page)
  expect(current.stock[0].amount).toBe(2)
  expect(current.stock[1].amount).toBe(0.5)
  expect(current.items).toHaveLength(2)
  expect(current.requests.filter(([method]: string[]) => method !== 'GET')).toEqual([['POST', 'stock/products/10/consume', { amount: 0.5, stock_entry_id: 'batch-cupboard', location_id: 2, spoiled: false, allow_subproduct_substitution: false }]])
})

