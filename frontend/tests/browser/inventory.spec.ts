for (const mode of ['write', 'reload', 'persisted-timeout']) {
  test(`stock ${mode} failure locks changes until explicit refresh and never retries`, async ({ page }) => {
    await buyMilk(page)
    if (mode === 'persisted-timeout') {
      await page.route('**/api/inventory/products/10/add', async route => {
        expect((await route.fetch()).ok()).toBeTruthy()
        await route.fulfill({ status: 502, body: 'SECRET after save' })
      })
    } else await page.request.post(`/_test/failure/${mode}`)
    await page.getByRole('button', { name: 'Review addition', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm addition', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Changes are paused')
    await expect(page.getByRole('alert')).not.toContainText('SECRET')
    await expect(page.getByRole('button', { name: 'Review addition', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Refresh inventory', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Review addition', exact: true })).toBeEnabled()
    await expect(page.getByLabel('Quantity bought', { exact: false })).toHaveValue('2')
    const current = await state(page)
    expect(current.stock).toHaveLength(mode === 'write' ? 2 : 3)
    expect(current.requests.filter(([method]: string[]) => method === 'POST')).toHaveLength(mode === 'write' ? 0 : 1)
    expect(current.items).toHaveLength(2)
  })
}

test('pending confirmation prevents duplicate stock submissions', async ({ page }) => {
  await buyMilk(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/inventory/products/10/add', async route => { await gate; await route.continue() })
  await page.getByRole('button', { name: 'Review addition', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm addition', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Confirm addition', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Refresh inventory', exact: true })).toBeDisabled()
  release()
  await expect(page.locator('.inventory-status')).toContainText('Added 2 bottle')
  expect((await state(page)).requests.filter(([method]: string[]) => method === 'POST')).toHaveLength(1)
})

test('never-expiring stock is explicit and an empty inventory has a useful next step', async ({ page }) => {
  await page.route('**/api/inventory', route => route.fulfill({ json: { today: '2026-11-15', products: [], track_dates: true, track_locations: true } }))
  await page.goto('/#inventory')
  await expect(page.getByRole('heading', { name: 'Your pantry is empty.' })).toBeVisible()
  await page.unroute('**/api/inventory')
  await page.getByRole('button', { name: 'I bought some', exact: true }).first().click()
  await page.getByLabel('Find a product', { exact: true }).fill('Tea')
  await page.getByRole('list', { name: 'Product results' }).getByRole('button', { name: 'Tea', exact: false }).click()
  await page.getByLabel('This has no expiry date').check()
  await page.getByRole('button', { name: 'Review addition', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Review inventory change' })).toContainText('No expiry date')
  await page.getByRole('button', { name: 'Confirm addition', exact: true }).click()
  await expect(page.locator('.inventory-status')).toContainText('Added 1 bottle of Tea')
  expect((await state(page)).stock[2].best_before_date).toBe('2999-12-31')
})


