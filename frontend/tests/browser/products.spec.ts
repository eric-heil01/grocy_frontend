for (const mode of ['write','reload']) {
  test(`requires a fresh read after ${mode} failure and never retries creation`, async ({ page }) => {
    await openProducts(page)
    await fillNew(page)
    await page.request.post(`/_test/failure/${mode}`)
    await page.getByRole('button', { name: 'Save product', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Saving is paused')
    await expect(page.getByRole('alert')).not.toContainText('SECRET')
    await expect(page.getByRole('button', { name: 'Save product', exact: true })).toBeDisabled()
    await page.getByRole('dialog').getByRole('button', { name: 'Refresh products', exact: true }).click()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Add product', exact: true })).toBeEnabled()
    const state = await (await page.request.get('/_test/state')).json()
    expect(state.products).toHaveLength(mode === 'reload' ? 4 : 3)
    expect(state.requests.filter(([method]: string[]) => method === 'POST')).toHaveLength(mode === 'reload' ? 1 : 0)
  })
}

test('pending product save disables duplicate submits and navigation', async ({ page }) => {
  await openProducts(page)
  await fillNew(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/product-catalog', async route => {
    if (route.request().method() === 'POST') await gate
    await route.continue()
  })
  await page.getByRole('button', { name: 'Save product', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save product', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled()
  release()
  await showSaved(page, 'Coffee')
})

test('rejects stale edits without overwriting external changes', async ({ page }) => {
  await openProducts(page)
  await browse(page).getByRole('button', { name:'Milk', exact:false }).click()
  await page.getByRole('button', { name:'Edit product', exact:true }).click()
  const current = await (await page.request.get('/api/product-catalog/10')).json()
  expect((await page.request.patch('/api/product-catalog/10', { data:{expected_version:current.version,name:'Changed elsewhere'} })).ok()).toBeTruthy()
  await page.getByLabel('What is it called?').fill('My changed milk')
  await page.getByRole('button', { name:'Save product', exact:true }).click()
  await expect(page.getByRole('alert')).toContainText('changed since you opened it')
  await page.getByRole('button', { name:'Refresh products', exact:true }).click()
  await expect(browse(page)).toContainText('Changed elsewhere')
})

