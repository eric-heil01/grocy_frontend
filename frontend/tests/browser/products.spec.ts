test('an edit saved before a connection failure stays locked until refreshed', async ({ page }) => {
  await openProducts(page)
  await browse(page).getByRole('button', { name:'Milk', exact:false }).click()
  await page.getByRole('button', { name:'Edit product', exact:true }).click()
  await page.getByLabel('What is it called?').fill('Whole milk')
  await page.route('**/api/product-catalog/10', async route => {
    if (route.request().method() !== 'PATCH') return route.continue()
    expect((await route.fetch()).ok()).toBeTruthy()
    await route.fulfill({ status:502,body:'SECRET after write' })
  })
  await page.getByRole('button', { name:'Save product', exact:true }).click()
  await expect(page.getByRole('alert')).toContainText('Saving is paused')
  await expect(page.getByRole('button', { name:'Save product', exact:true })).toBeDisabled()
  await page.getByRole('button', { name:'Refresh products', exact:true }).click()
  await expect(browse(page)).toContainText('Whole milk')
  const state = await (await page.request.get('/_test/state')).json()
  expect(state.requests.filter(([method]: string[]) => method === 'PUT')).toHaveLength(1)
})

