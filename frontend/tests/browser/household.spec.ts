test('phone and tablet layouts keep navigation and dialog controls within the viewport', async ({ page }, testInfo) => {
  for (const width of [320, 768]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await page.getByRole('button', { name: 'Add product', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog.getByLabel('What is it called?')).toBeFocused()
    const bounds = await dialog.boundingBox()
    expect(bounds!.width).toBeLessThanOrEqual(width)
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    if (width === 320) {
      expect(bounds!.height).toBeGreaterThanOrEqual(890)
      expect(bounds!.y).toBe(0)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: testInfo.outputPath(`creation-${width}.png`) })
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Add product', exact: true })).toBeFocused()
  }
})

