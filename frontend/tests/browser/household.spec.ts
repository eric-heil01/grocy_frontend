import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

const navigation = (page: Page) => page.getByRole('navigation', { name: 'Main navigation', exact: true })
const state = async (page: Page) => (await page.request.get('/_test/state')).json()

test.beforeEach(async ({ request }) => { expect((await request.post('/_test/reset')).ok()).toBeTruthy() })

test('shared navigation has active labels and mobile bottom placement across major screens', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page.getByRole('navigation', { name: 'Household shortcuts' }).getByRole('link')).toHaveCount(3)
  for (const [label, heading] of [['Groceries', 'Your grocery list.'], ['Meals', 'Plan your dinners.'], ['Products', 'Your products.'], ['Home', 'Your household, at a glance.']]) {
    await navigation(page).getByRole('link', { name: label, exact: true }).click()
    await expect(page.getByRole('heading', { name: heading, exact: true })).toBeVisible()
    await expect(navigation(page).getByRole('link', { name: label, exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('button', { name: 'Add product', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  if (testInfo.project.name.includes('mobile')) {
    const bar = page.locator('.mobile-navigation')
    await expect(bar).toBeVisible()
    const bounds = await bar.boundingBox()
    expect(Math.abs(bounds!.y + bounds!.height - page.viewportSize()!.height)).toBeLessThan(2)
    for (const link of await bar.getByRole('link').all()) {
      const box = await link.boundingBox()
      expect(box!.height).toBeGreaterThanOrEqual(48)
      await expect(link.locator('svg')).toHaveCount(1)
    }
  } else await expect(page.locator('.mobile-navigation')).not.toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('household-home.png'), fullPage: true })
})

