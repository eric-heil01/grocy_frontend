test('an unavailable product catalog can recover without losing the grocery draft', async ({ page }) => {
  let fail = true
  await page.route('**/api/product-catalog', route => fail ? route.fulfill({ status: 503, body: 'unavailable' }) : route.continue())
  await page.goto('/#groceries')
  await page.getByLabel('Quantity', { exact: true }).fill('2')
  await page.getByLabel('Note (optional)').fill('Keep this')
  await page.getByLabel('Find a product', { exact: true }).fill('Eggs')
  await page.getByRole('button', { name: 'Create new product', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('alert')).toContainText('could not be loaded')
  fail = false
  await dialog.getByRole('button', { name: 'Refresh products', exact: true }).click()
  await expect(dialog.getByLabel('What is it called?')).toHaveValue('Eggs')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByLabel('Quantity', { exact: true })).toHaveValue('2')
  await expect(page.getByLabel('Note (optional)')).toHaveValue('Keep this')
  expect((await state(page)).requests.filter(([method]: string[]) => method !== 'GET')).toEqual([])
})

test('an uncertain creation is reviewed and selected after refresh without repeating the write', async ({ page }) => {
  await page.goto('/#groceries')
  await page.getByLabel('Find a product', { exact: true }).fill('Eggs')
  await page.getByLabel('Quantity', { exact: true }).fill('2')
  await page.getByLabel('Note (optional)').fill('Large eggs')
  await page.getByRole('button', { name: 'Create new product', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('How do you count or measure it?').selectOption('5')
  await dialog.getByLabel('Where do you normally keep it?').selectOption('2')
  await page.route('**/api/product-catalog', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    expect((await route.fetch()).ok()).toBeTruthy()
    await route.fulfill({ status: 502, body: 'SECRET failed after write' })
  })
  await dialog.getByRole('button', { name: 'Save product', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Saving is paused')
  await expect(dialog.getByRole('alert')).not.toContainText('SECRET')
  await expect(dialog.getByLabel('What is it called?')).toHaveValue('Eggs')
  await expect(dialog.getByRole('button', { name: 'Save product', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Refresh products', exact: true }).click()
  await expect(dialog.getByText('This product already exists.', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Use Eggs', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Selected: Eggs', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Quantity', { exact: false })).toHaveValue('2')
  await expect(page.getByLabel('Note (optional)')).toHaveValue('Large eggs')
  const current = await state(page)
  expect(current.items).toHaveLength(2)
  expect(current.requests.filter(([method]: string[]) => method === 'POST')).toHaveLength(1)
})

